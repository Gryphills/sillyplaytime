function saveStorage(dragon, status) {
    let dragonvaleEventStorage = JSON.parse(localStorage.getItem("dragonvaleEventStorage"));
    dragonvaleEventStorage.dragonInfo[dragon].status = status
    localStorage.setItem("dragonvaleEventStorage", JSON.stringify(dragonvaleEventStorage));
}

